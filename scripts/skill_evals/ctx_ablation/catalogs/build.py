#!/usr/bin/env python3
"""The step-1 eval catalogs (BRO-2674 pre-flip): role-x's shipped reflex catalog with
only the fields the measurement varies changed, so two arms differ in line text alone.

* ``step1-reworded.yaml``: the shipped catalog, with the entries step 1 measures set to
  ``routed`` (their line has to be delivered to be measured; the v2 gate lists heal).
* ``step1-v1lines.yaml``: the same, with those entries' lines put back to their text at
  9d24559 (skills#253, v1).

    python3 scripts/skill_evals/ctx_ablation/catalogs/build.py

A test rebuilds both and fails if the committed files differ, or if either differs from
the shipped catalog in anything but these fields.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
SHIPPED = HERE.parents[3] / "skills" / "orchestration" / "role-x" / "references" / "reflexes.yaml"

#: Entries step 1 measures, forced to ``routed`` in both eval catalogs.
MEASURED = ("p9.heal-on-red", "convention.paseo-fleet-listing", "p10.worktree-removal-guard")

#: Each measured entry's line at 9d24559, as it is written in the YAML.
V1_LINES = {
    "p9.heal-on-red": "When a PR's checks fail, the stack runs `p9 heal <pr> --classify` before editing or "
                      "asking, applies a classified heal inside the PR diff, then re-arms `p9 watch`.",
    "convention.paseo-fleet-listing": "The whole Paseo fleet is `list_agents(cwd:\\\"/\\\", limit:200)`; the "
                                      "default call sees only the caller's cwd subtree and stops at 50.",
    "p10.worktree-removal-guard": "Before a worktree is removed (`git worktree remove`, `claude rm`, "
                                  "`archive_workspace`), the stack copies out its ignored files (`git status "
                                  "--ignored`: `.env*`, `*.db`) and runs `lsof +D <path>`.",
}

HEADER = "# GENERATED by scripts/skill_evals/ctx_ablation/catalogs/build.py from {src}; do not edit.\n"


def _entries(text: str) -> list[tuple[str | None, list[str]]]:
    out: list[tuple[str | None, list[str]]] = [(None, [])]
    for line in text.splitlines(keepends=True):
        if line.startswith("  - id: "):
            out.append((line.split(":", 1)[1].strip(), []))
        out[-1][1].append(line)
    return out


def build(v1_lines: bool) -> str:
    parts = []
    for rid, lines in _entries(SHIPPED.read_text(encoding="utf-8")):
        if rid in MEASURED:
            lines = ["    status: routed\n" if ln.startswith("    status: ") else ln for ln in lines]
            if v1_lines:
                lines = [f'    line: "{V1_LINES[rid]}"\n' if ln.startswith("    line: ") else ln for ln in lines]
        parts.extend(lines)
    return HEADER.format(src="skills/orchestration/role-x/references/reflexes.yaml") + "".join(parts)


TARGETS = {"step1-reworded.yaml": False, "step1-v1lines.yaml": True}

if __name__ == "__main__":
    for name, v1 in TARGETS.items():
        (HERE / name).write_text(build(v1), encoding="utf-8")
        print(f"wrote {HERE / name}")
