#!/usr/bin/env python3
"""Generate the Claude Code and Codex plugin manifests for the broomva/skills monorepo.

Four files are written, all derived from `skills/<category>/<name>/SKILL.md`
on disk. Both harnesses get the same plugin set, the `broomva-skills` bundle
plus one plugin per category bucket (`governance`, `design`, ...):

  * `.claude-plugin/marketplace.json` — Claude Code. Each bucket plugin is
    rooted at `skills/<category>/` with `strict: false` and `skills: ["./"]`.
  * `.claude-plugin/plugin.json` — Claude Code's bundle manifest. It lists
    every bucket under `skills`, because default discovery only looks one level
    into `skills/` and our skills sit two levels down.
  * `.agents/plugins/marketplace.json` — Codex. Codex rejects `skills: "./"`
    and drops symlinks on install, so each bucket plugin is rooted at `skills/`
    (which has no manifest) with `skills: "./<category>/"`. Rooting it at the
    repo instead would make Codex read the bundle's manifest and refuse the
    name mismatch.
  * `.codex-plugin/plugin.json` — Codex's bundle manifest, `skills: "./skills/"`
    (Codex discovers skills recursively below it).

No `version` is written. Claude Code then versions a git-sourced plugin by
commit SHA, so `/plugin update` follows main the same way `npx skills add`
does; per-skill versions stay in each SKILL.md.

Category titles come from the README's `### <Title> — `skills/<category>/``
headings, which `lint_skill_catalog.py` already keeps in step with disk. A
bucket with no heading falls back to its directory name.

    python3 scripts/build_plugin_marketplace.py           # rewrite all four files
    python3 scripts/build_plugin_marketplace.py --check   # exit 1 on drift

Pure stdlib; no network.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]

MARKETPLACE_NAME = "broomva-skills"
BUNDLE_NAME = "broomva-skills"
OWNER = {"name": "Broomva", "url": "https://github.com/broomva"}
HOMEPAGE = "https://github.com/broomva/skills"

#: `### Governance & control — `skills/governance/``
_HEADING = re.compile(r"^### (?P<title>.+?) — `skills/(?P<cat>[a-z0-9-]+)/`\s*$", re.M)


def discover(root: Path) -> dict[str, list[str]]:
    """`{category: [skill, ...]}` for every depth-2 SKILL.md, both sorted."""
    out: dict[str, list[str]] = {}
    for skill_md in sorted((root / "skills").glob("*/*/SKILL.md")):
        category, name = skill_md.parts[-3], skill_md.parts[-2]
        out.setdefault(category, []).append(name)
    return {c: sorted(n) for c, n in sorted(out.items())}


def titles(root: Path) -> dict[str, str]:
    readme = root / "README.md"
    text = readme.read_text(encoding="utf-8") if readme.exists() else ""
    return {m["cat"]: m["title"] for m in _HEADING.finditer(text)}


def build(root: Path) -> dict[str, dict]:
    """The four manifests as `{relative path: json object}`."""
    cats = discover(root)
    if not cats:
        raise SystemExit(f"no skills found under {root / 'skills'}")
    names = titles(root)
    total = sum(len(v) for v in cats.values())

    bundle_desc = (
        f"Every broomva/skills skill in one plugin: {total} skills across "
        f"{len(cats)} category buckets. Large always-on footprint; prefer "
        "the per-category plugins when you only need a few."
    )
    cat_desc = {
        cat: f"{names.get(cat, cat)} skills from broomva/skills: {', '.join(skills)}."
        for cat, skills in cats.items()
    }
    market_desc = (
        f"The broomva/skills monorepo as plugins: one per category bucket ({len(cats)}), "
        f"plus `{BUNDLE_NAME}` with all {total} skills."
    )
    plugin_desc = (
        f"All {total} broomva/skills agent skills ({len(cats)} category buckets) "
        "as one plugin. Generated by scripts/build_plugin_marketplace.py."
    )

    claude_market = {
        "name": MARKETPLACE_NAME,
        "description": market_desc,
        "owner": OWNER,
        "plugins": [{
            "name": BUNDLE_NAME,
            "description": bundle_desc,
            "source": "./",
            "category": "productivity",
            "tags": ["skills", "bundle"],
        }] + [{
            "name": cat,
            "description": cat_desc[cat],
            "source": f"./skills/{cat}",
            "strict": False,
            "skills": ["./"],
            "category": "productivity",
            "tags": ["skills", cat],
        } for cat in cats],
    }
    claude_plugin = {
        "name": BUNDLE_NAME,
        "description": plugin_desc,
        "author": OWNER,
        "homepage": HOMEPAGE,
        "repository": HOMEPAGE,
        "license": "MIT",
        "keywords": ["skills", "agent-skills", *cats],
        "skills": [f"./skills/{cat}" for cat in cats],
    }

    policy = {"installation": "AVAILABLE", "authentication": "ON_INSTALL"}
    codex_market = {
        "name": MARKETPLACE_NAME,
        "interface": {"displayName": "Broomva Skills"},
        "plugins": [{
            "name": BUNDLE_NAME,
            "description": bundle_desc,
            "source": {"source": "local", "path": "./"},
            "policy": policy,
            "category": "Productivity",
        }] + [{
            "name": cat,
            "description": cat_desc[cat],
            "source": {"source": "local", "path": "./skills"},
            "skills": f"./{cat}/",
            "policy": policy,
            "category": "Productivity",
        } for cat in cats],
    }
    codex_plugin = {
        "name": BUNDLE_NAME,
        "description": plugin_desc,
        "author": OWNER,
        "homepage": HOMEPAGE,
        "repository": HOMEPAGE,
        "license": "MIT",
        "keywords": ["skills", "agent-skills", *cats],
        "skills": "./skills/",
        "interface": {
            "displayName": "Broomva Skills",
            "shortDescription": "Every broomva/skills agent skill",
            "longDescription": market_desc,
            "developerName": OWNER["name"],
            "category": "Productivity",
            "websiteURL": HOMEPAGE,
        },
    }
    return {
        ".claude-plugin/marketplace.json": claude_market,
        ".claude-plugin/plugin.json": claude_plugin,
        ".agents/plugins/marketplace.json": codex_market,
        ".codex-plugin/plugin.json": codex_plugin,
    }


def render(obj: dict) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="report drift, write nothing")
    ap.add_argument("--root", type=Path, default=_REPO_ROOT, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    drift = []
    for rel, obj in build(args.root).items():
        path = args.root / rel
        want = render(obj)
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have == want:
            continue
        if args.check:
            drift.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want, encoding="utf-8")
            print(f"wrote {rel}")

    if drift:
        for rel in drift:
            print(f"DRIFT {rel} does not match skills/ on disk", file=sys.stderr)
        print("fix: python3 scripts/build_plugin_marketplace.py", file=sys.stderr)
        return 1
    if args.check:
        print("plugin manifests match skills/ on disk")
    return 0


if __name__ == "__main__":
    sys.exit(main())
