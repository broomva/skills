def clean(tmp_path: Path) -> Path:
    (tmp_path / "main.js").write_text("module.exports = class Plugin {}\n")
    (tmp_path / "manifest.json").write_text('{"id": "x"}\n')
    (tmp_path / "README.md").write_text("Install into <vault>/.obsidian/plugins/x\n")
    return tmp_path


def test_clean_mod_passes(clean: Path):
    assert pc.scan(clean) == []
    r = subprocess.run([sys.executable, str(SCRIPT), str(clean)], capture_output=True, text=True)
    assert r.returncode == 0 and r.stdout.startswith("OK")


@pytest.mark.parametrize("name", ["app.asar", "libfoo.dylib", "game.z64", "data.pak"])
def test_third_party_binaries_block(clean: Path, name: str):
    (clean / name).write_bytes(b"\x00\x01")
    assert ("binary", name) in kinds(clean)


def test_app_bundle_directory_blocks_and_is_not_descended(clean: Path):
    (clean / "Target.app" / "Contents").mkdir(parents=True)
    (clean / "Target.app" / "Contents" / "x.dylib").write_bytes(b"\x00")
    found = kinds(clean)
    assert ("binary", "Target.app") in found
    assert not any(p.startswith("Target.app/") for _, p in found)


def test_allow_glob_exempts(clean: Path):
    (clean / "assets").mkdir()
