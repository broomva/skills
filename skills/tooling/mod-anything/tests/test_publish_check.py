@pytest.mark.skipif(os.geteuid() == 0, reason="root can read mode-000 files")
def test_unreadable_file_is_exit_2_not_clean(clean: Path):
    f = clean / "locked.txt"
    f.write_text("x")
    f.chmod(0)
    try:
        with pytest.raises(pc.Unreadable):
            pc.scan(clean, hostnames=set(), username=None)
        r = subprocess.run([sys.executable, str(SCRIPT), str(clean)], capture_output=True, text=True)
        assert r.returncode == 2 and "cannot read" in r.stderr
    finally:
        f.chmod(_stat.S_IRUSR | _stat.S_IWUSR)


