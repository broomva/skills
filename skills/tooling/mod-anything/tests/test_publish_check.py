import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "publish_check.py"
spec = importlib.util.spec_from_file_location("publish_check", SCRIPT)
pc = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pc)


def kinds(root: Path, **kw) -> set[tuple[str, str]]:
    kw.setdefault("hostnames", set())
    kw.setdefault("username", None)
    return {(f["kind"], f["path"]) for f in pc.scan(root, **kw)}


