#!/usr/bin/env node
// Generate assets/tokens/tokens.css from assets/tokens/tokens.json (the single source of truth).
//   node scripts/build_tokens.mjs           write tokens.css
//   node scripts/build_tokens.mjs --check   exit 1 if tokens.css is stale (CI and the tests run this)
// Every colour is emitted twice: an sRGB hex fallback, then the canonical OKLCH inside @supports.
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = join(HERE, "../assets/tokens/tokens.json");
export const TOKENS_CSS = join(HERE, "../assets/tokens/tokens.css");

/** Parse `oklch(L C H)` or `oklch(L C H / A)` into numbers. Throws on anything else. */
export function parseOklch(s) {
  const m = /^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+))?\s*\)$/.exec(String(s).trim());
  if (!m) throw new Error(`not an oklch() colour: ${s}`);
  return { L: +m[1], C: +m[2], H: +m[3], A: m[4] === undefined ? 1 : +m[4] };
}

/** OKLCH → linear sRGB (Björn Ottosson's OKLab matrices). */
export function oklchToLinear({ L, C, H }) {
  const h = (H * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}

const clamp01 = (v) => Math.min(1, Math.max(0, v));
const encode = (v) => (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);

/** OKLCH string → `#rrggbb` or `#rrggbbaa` (gamut-clipped). */
export function oklchToHex(s) {
  const c = parseOklch(s);
  const hex = (v) =>
    Math.round(clamp01(v) * 255)
      .toString(16)
      .padStart(2, "0");
  const rgb = oklchToLinear(c).map((v) => hex(encode(clamp01(v))));
  return `#${rgb.join("")}${c.A < 1 ? hex(c.A) : ""}`;
}

/** WCAG 2 relative luminance of an opaque OKLCH colour. */
export function luminance(s) {
  const [r, g, b] = oklchToLinear(parseOklch(s)).map(clamp01);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG 2 contrast ratio between two opaque OKLCH colours. */
export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

/** Flatten tokens.json into [cssVarName, {dawn, dusk}] pairs. */
export function colorVars(tokens) {
  const out = [];
  for (const [k, v] of Object.entries(tokens.color)) out.push([`--ld-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.nature)) out.push([`--ld-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.metal)) out.push([`--ld-metal-${k}`, v]);
  return out;
}

function block(selector, vars, mode, fmt) {
  return `${selector} {\n${vars.map(([n, v]) => `  ${n}: ${fmt(v[mode])};`).join("\n")}\n}\n`;
}

export function buildCss(tokens) {
  const vars = colorVars(tokens);
  const id = (v) => v;
  const statics = [
    `  --ld-font-display: ${tokens.type.display};`,
    `  --ld-font-text: ${tokens.type.text};`,
    `  --ld-font-mono: ${tokens.type.mono};`,
    ...Object.entries(tokens.radius).map(([k, v]) => `  --ld-r-${k}: ${v}px;`),
    `  --ld-ua-speed: ${tokens.motion.ua.degPerSecond};`,
  ].join("\n");
  const dusk = '[data-ld-mode="dusk"]';
  return [
    "/* Liquid Dawn tokens. GENERATED by scripts/build_tokens.mjs from tokens.json: do not edit by hand. */",
    "/* Modes: dawn (default, :root) · dusk ([data-ld-mode=dusk]). To follow the OS, call followOS() from the kit. */",
    `:root {\n${statics}\n  color-scheme: light;\n}`,
    `${dusk} {\n  color-scheme: dark;\n}`,
    block(":root", vars, "dawn", oklchToHex),
    block(dusk, vars, "dusk", oklchToHex),
    "@supports (color: oklch(0 0 0)) {",
    block(":root", vars, "dawn", id).replace(/^/gm, "  "),
    block(dusk, vars, "dusk", id).replace(/^/gm, "  "),
    "}",
    "",
  ].join("\n");
}

const isMain = (() => {
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
})();

if (isMain) {
  const css = buildCss(JSON.parse(readFileSync(TOKENS_JSON, "utf8")));
  if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = readFileSync(TOKENS_CSS, "utf8");
    } catch {}
    if (cur !== css) {
      console.error("tokens.css is stale: run node scripts/build_tokens.mjs");
      process.exit(1);
    }
    console.log("tokens.css is up to date");
  } else {
    writeFileSync(TOKENS_CSS, css);
    console.log(`wrote ${TOKENS_CSS}`);
  }
}
